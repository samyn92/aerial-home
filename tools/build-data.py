"""Generate the scene data: the streamable library and the list of stored scenes.

Usage: python3 tools/build-data.py
Reads tools/catalog/videos.json (the Aerial screensaver catalogue), its en-GB/de-DE
name tables and tools/catalog/previews.json (Apple's preview images, see
fetch-previews.py), and writes app/data.js.

Also writes media/scenes/scenes.json from tools/scenes.tsv: the clips that
push-scenes.sh stores on the TV, which the app reads from there at start.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "tools", "catalog")


def names(lang):
    return json.load(open(os.path.join(CATALOG, lang + ".json")))["strings"]


en, de = names("en-GB"), names("de-DE")
assets = json.load(open(os.path.join(CATALOG, "videos.json")))["assets"]
previews = json.load(open(os.path.join(CATALOG, "previews.json")))

library = []
for a in assets:
    key = a.get("localizedNameKey")
    # Only HTTPS: a plain-HTTP stream could be swapped by anyone on the network path.
    urls = {k: a[k] for k in ("url-4K-SDR", "url-1080-SDR", "url-1080-H264") if a.get(k, "").startswith("https://")}
    if not en.get(key) or not urls:
        continue
    scene = {
        "id": a["id"],
        "title": {"en": en[key], "de": de.get(key, en[key])},
        "source": "apple" if "apple.com" in urls.get("url-4K-SDR", "") else "community",
        "urls": urls,
    }
    # The TV fetches Apple's preview once (see previews in app.js); scenes without one get a placeholder.
    if previews.get(a["id"].upper()):
        scene["preview"] = previews[a["id"].upper()]
    library.append(scene)
library.sort(key=lambda s: s["title"]["en"])

out = os.path.join(ROOT, "app", "data.js")
with open(out, "w") as f:
    f.write("// Generated by tools/build-data.py. Do not edit.\n")
    f.write("window.AERIAL_DATA = ")
    json.dump({"library": library}, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(f"{out}: {len(library)} library scenes, {sum(1 for s in library if 'preview' in s)} with previews")

# Stored scenes reuse the library's German name when the same place exists there.
by_en = {s["title"]["en"]: s["title"]["de"] for s in library}
scenes = []
tsv = os.path.join(ROOT, "tools", "scenes.tsv")
if os.path.exists(tsv):
    for line in open(tsv):
        if not line.strip() or line.startswith("#"):
            continue
        slug, title, _ = line.rstrip("\n").split("\t")
        scenes.append({"slug": slug, "title": {"en": title, "de": by_en.get(title, title)}})
os.makedirs(os.path.join(ROOT, "media", "scenes"), exist_ok=True)
out = os.path.join(ROOT, "media", "scenes", "scenes.json")
with open(out, "w") as f:
    json.dump(scenes, f, ensure_ascii=False, indent=1)
print(f"{out}: {len(scenes)} stored scenes")
